# Curved black arrow (rad controls how much the arrow curves)
arrow = dict(arrowstyle="->", color="black", linewidth=3,
             connectionstyle="arc3,rad=0.3")

# point an arrow at a holiday's data point, with the label placed nearby
def label(text, date, text_date, text_y):
    i = np.where(x == np.datetime64(date))[0][0]
    plt.annotate(text, xy=(x[i], y_1[i]),
                 xytext=(np.datetime64(text_date), text_y),
                 arrowprops=arrow)

# holiday labels
