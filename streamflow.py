import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

# define variables
L = 6        # ft
R_A = 170    # lb
R_B = 410    # lb
P_1 = 100    # lb
q_1 = 120    # lb/ft
q_2 = 120    # lb/ft

# define x with arguments
x = np.linspace(0, L, 500)

# define V
V = np.zeros_like(x)

# for loop piecewise function
for i in range(len(x)):
    if x[i] < 2:
        V[i] = R_A - (q_1 * x[i])
    elif x[i] < 4:
        V[i] = R_A - (q_1 * 2) - P_1
    else:
        V[i] = R_A - (q_1 * 2) - P_1 + R_B - (q_2 * (x[i] - 4))

# plot results - AI assisted with matching the plot elements
plt.plot(x, V)
plt.fill_between(x, V, color="lightblue", alpha=0.8)
plt.axhline(0, color="black", linewidth=1)
plt.title("Shear Diagram")
plt.xlabel("x (ft)")
plt.ylabel("V (lb)")
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

# define variables
L = 6
R_A = 170
R_B = 410
P_1 = 100
q_1 = 120
q_2 = 120

# define x and M
x = np.linspace(0, L, 500)
M = np.zeros_like(x)

# for loop - piecewise moment function
for i in range(len(x)):
    if x[i] < 2:
        M[i] = (R_A * x[i]) - (q_1 * x[i]**2 / 2)
    elif x[i] < 4:
        M[i] = (R_A * x[i]) - (q_1 * 2 * (x[i] - 1)) - (P_1 * (x[i] - 2))
    else:
        M[i] = ((R_A * x[i]) - (q_1 * 2 * (x[i] - 1)) - (P_1 * (x[i] - 2))
                + (R_B * (x[i] - 4)) - (q_2 * (x[i] - 4) * ((x[i] - 4) / 2)))

# plot chart - AI assisted with matching elements
plt.plot(x, M)
plt.fill_between(x, M, color="lightblue", alpha=0.8)
plt.axhline(0, color="black", linewidth=1)
plt.title("Moment Diagram")
plt.xlabel("x (ft)")
plt.ylabel("M (lb-ft)")
plt.show()

